print("Вы стоите на распутье. Куда пойдёте?")
choice = input("Введите направление (налево/направо/прямо): ").strip().lower()

if choice == "налево" or choice == "влево":
    print("Пойдёшь налево — коня потеряешь.")
elif choice == "направо" or choice == "вправо":
    print("Пойдёшь направо — себя потеряешь.")
elif choice == "прямо":
    print("Пойдёшь прямо — богатым будешь.")
else:
    print("Не понял направление. Введите: налево, направо или прямо.")
